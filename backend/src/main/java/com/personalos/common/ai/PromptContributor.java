package com.personalos.common.ai;

/**
 * 系统提示贡献者 SPI。
 *
 * <h2>为什么需要这一层间接</h2>
 * 对话模块需要把各业务模块的上下文拼进系统提示（例如「关于用户的长期记忆」），
 * 但它**不应该**依赖具体业务模块 —— 理由与 {@link ToolContributor} 完全相同：
 * 否则会出现业务模块反向依赖对话模块，且每新增一类上下文（记忆、天气、当前日程……）
 * 都要回头改对话模块。
 *
 * <p>有了本接口，{@code chat} 只依赖 {@code common}；业务模块实现它并注册为 Bean 即可。
 *
 * <h2>实现约定</h2>
 * <ul>
 *   <li>返回值会以「空行 + 内容」的形式追加在基础系统提示之后。</li>
 *   <li><b>无内容时必须返回空串</b>（而不是 {@code null} 或「暂无」这类占位文案）——
 *       调用方据此决定是否追加，返回占位文案会让系统提示里凭空多出一段无意义文字。</li>
 *   <li>实现方自己负责长度预算：系统提示的体量直接决定上下文成本与模型注意力。</li>
 * </ul>
 */
public interface PromptContributor {

    /**
     * @return 要追加到系统提示的文本；无内容时返回空串
     */
    String contribute();

    /**
     * 带「本轮用户输入」的版本（2026-10-26）。
     *
     * <p>为什么要多一个参数：上下文是否相关，取决于用户在问什么。长期记忆如果只按
     * 「最近修改时间」全塞，用户在问日程时也会收到一堆无关的偏好约束 —— 既浪费预算，
     * 也会稀释模型对真正相关内容的注意力。
     *
     * <p>默认实现直接委托给无参版本，因此**既有的贡献者不需要改动**；
     * 有能力做相关性筛选的实现自己覆盖它即可。
     *
     * @param userInput 本轮用户消息原文，可能为空串
     * @return 要追加到系统提示的文本；无内容时返回空串
     */
    default String contribute(String userInput) {
        return contribute();
    }
}
