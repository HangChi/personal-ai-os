package com.personalos.memory.entity;

/**
 * 记忆来源（V13）。
 *
 * <p>存在的唯一理由是**可审计**：自动沉淀是模型自行判断的写入，
 * 与用户显式要求保存在一起时，必须能事后分清「这条是谁写的」，
 * 否则既排查不了模型的误判，也没法批量清理。
 *
 * <p>编辑不改变来源：它记录的是「最初由谁写入」。
 * 用户改过一条自动记忆后仍标 AUTO 是刻意的 —— 那恰恰说明它当初被写错过。
 */
public enum MemorySource {

    /** 用户显式保存（REST 或助手通过 saveMemory 工具） */
    MANUAL,

    /** 轮末自动沉淀（模型从对话中抽取） */
    AUTO
}
