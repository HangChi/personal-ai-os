-- ============================================================
-- V14: 阶段 22 —— 消息附件
--
-- 背景：输入区增加了「添加附件」，选中的文件需要随消息持久化，
-- 否则刷新页面后附件凭空消失（与「历史不得被裁剪」是同一条要求）。
--
-- 设计要点：
--   1) 存 **JSON 数组**而不是关联表：附件元数据（id/文件名/类型/大小）是不可变的快照，
--      没有「按附件查询」的消费方，为它建表 + 外键 + 关联查询是纯负担。
--   2) 文件本体**不入库**：落盘在 backend/data/uploads/<uuid>，库里只留定位与元数据。
--      数据库存大字段会拖慢每一次消息查询，而消息查询是对话页的高频路径。
--   3) 允许 NULL：既有消息没有附件，语义即「无附件」，无需回填空数组。
-- ============================================================

ALTER TABLE chat_message
    ADD COLUMN IF NOT EXISTS attachments TEXT;

COMMENT ON COLUMN chat_message.attachments IS '附件元数据 JSON 数组（id/文件名/类型/大小）；文件本体在 backend/data/uploads/';
