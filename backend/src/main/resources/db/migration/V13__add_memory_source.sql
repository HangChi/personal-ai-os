-- ============================================================
-- V13: 阶段 22 收尾 —— 记忆来源标记
--
-- 背景：阶段 22 增加了「记忆自动沉淀」（模型在轮末自行判断值得长期记住的内容）。
-- 但它写进来的记忆与用户手工保存的**完全无法区分**：出问题时既没法排查，
-- 也没法批量清理模型的误判。能审计的自动化才敢开着跑。
--
-- 取值：MANUAL（用户/助手经 REST 或工具显式保存）、AUTO（轮末自动沉淀）。
-- 用 VARCHAR 而非枚举类型：取值集合可能扩展（例如将来的 IMPORT），
-- 且 PostgreSQL 枚举值的增删需要额外迁移，代价大于收益。
--
-- 默认 MANUAL：既有数据全部是手工产生的，语义正确，无需回填。
-- ============================================================

ALTER TABLE memory
    ADD COLUMN IF NOT EXISTS source VARCHAR(16) NOT NULL DEFAULT 'MANUAL';

COMMENT ON COLUMN memory.source IS '记忆来源：MANUAL=显式保存，AUTO=轮末自动沉淀';
