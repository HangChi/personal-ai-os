import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { existsSync,writeFileSync } from 'node:fs'
import { join,dirname,resolve } from 'node:path'
import { fileURLToPath,pathToFileURL } from 'node:url'
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..')
const [backend,output,emptyEnv]=process.argv.slice(2)
assert.equal(new URL(backend).hostname,'127.0.0.1')
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE??join(process.env.HOME,'.workbuddy/binaries/node/workspace/node_modules/playwright'))
const {preview}=await import(pathToFileURL(join(root,'frontend/node_modules/vite/dist/node/index.js')))
const server=await preview({root:join(root,'frontend'),configFile:false,envDir:emptyEnv,preview:{host:'127.0.0.1',port:0,proxy:{'/api':{target:backend}}}})
const origin=`http://127.0.0.1:${server.httpServer.address().port}`
const executable=[1243,1234].map((v)=>join(process.env.HOME,`Library/Caches/ms-playwright/chromium_headless_shell-${v}/chrome-headless-shell-mac-arm64/chrome-headless-shell`)).find(existsSync)
let browser
const report={result:'FAIL',checks:[],errors:[]}
try{
 browser=await chromium.launch(executable?{executablePath:executable}:{channel:'chrome'})
 const context=await browser.newContext({viewport:{width:1365,height:1000},locale:'zh-CN',timezoneId:'Asia/Shanghai'})
 await context.route('**/*',(route)=>new URL(route.request().url()).origin===origin?route.continue():route.abort())
 const page=await context.newPage();page.setDefaultTimeout(15000)
 page.on('pageerror',(e)=>report.errors.push(String(e)))
 await page.goto(origin+'/tasks',{waitUntil:'networkidle'})
 await page.getByRole('button',{name:'管理项目',exact:true}).click()
 await page.getByLabel('新项目名称',{exact:true}).fill('浏览器测试项目')
 await page.getByRole('button',{name:'新建项目',exact:true}).click()
 await page.getByRole('row').filter({hasText:'浏览器测试项目'}).waitFor()
 await page.locator('.el-message').first().waitFor()
 assert.equal(await page.locator('.el-message').first().evaluate((el)=>getComputedStyle(el).position),'fixed','反馈提示应有完整样式')
 report.checks.push('项目创建与成功反馈样式')
 const org=page.locator('.task-create .task-organization')
 await org.locator('.el-select').nth(0).click()
 await page.getByRole('option',{name:'浏览器测试项目',exact:true}).click()
 await page.getByLabel('任务标题',{exact:true}).fill('浏览器父任务')
 await page.getByRole('button',{name:'新建任务',exact:true}).click()
 const parent=page.getByRole('row').filter({hasText:'浏览器父任务'})
 await parent.getByRole('button',{name:'添加子任务',exact:true}).click()
 await page.getByLabel('任务标题',{exact:true}).fill('浏览器子任务')
 await page.getByRole('button',{name:'新建任务',exact:true}).click()
 const child=page.getByRole('row').filter({hasText:'浏览器子任务'})
 await child.waitFor()
 await parent.getByRole('button',{name:'完成',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'请先完成所有子任务'}).waitFor()
 await child.getByRole('button',{name:'完成',exact:true}).click()
 await child.getByRole('button',{name:'恢复',exact:true}).waitFor()
 await parent.getByRole('button',{name:'完成',exact:true}).click()
 await parent.getByRole('button',{name:'恢复',exact:true}).waitFor()
 report.checks.push('子任务创建、父任务约束、先子后父完成')
 await page.getByLabel('任务标题',{exact:true}).fill('浏览器每日检查')
 const due=await page.evaluate(()=>{const d=new Date();return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')} 18:30`})
 await page.getByPlaceholder('选择截止时间',{exact:true}).fill(due)
 await page.getByPlaceholder('选择截止时间',{exact:true}).press('Tab')
 await org.locator('.el-select').nth(2).click()
 await page.getByRole('option',{name:'每天',exact:true}).click()
 await page.getByRole('button',{name:'新建任务',exact:true}).click()
 await page.getByRole('row').filter({hasText:'浏览器每日检查'}).waitFor()
 await page.screenshot({path:join(output,'tasks-desktop.png'),fullPage:true})
 await page.goto(origin+'/',{waitUntil:'networkidle'})
 const today=page.locator('.today-workspace__card').filter({has:page.getByRole('heading',{name:/今日任务/})})
 const todayRow=today.getByRole('listitem').filter({hasText:'浏览器每日检查'})
 await todayRow.waitFor()
 await todayRow.locator('.today-workspace__link').click()
 const editDialog=page.getByRole('dialog',{name:'编辑任务'})
 await editDialog.waitFor()
 assert.equal(await editDialog.getByPlaceholder('任务标题',{exact:true}).inputValue(),'浏览器每日检查')
 await editDialog.getByRole('button',{name:'取消',exact:true}).click()
 await page.goto(origin+'/',{waitUntil:'networkidle'})
 await todayRow.getByRole('button',{name:'完成',exact:true}).click();await todayRow.waitFor({state:'hidden'})
 report.checks.push('工作台定位任务编辑')
 const data=await (await page.request.get(origin+'/api/v1/tasks?keyword='+encodeURIComponent('浏览器每日检查'))).json()
 assert.equal(data.data.total,2)
 assert.equal(data.data.items.filter((t)=>t.status==='DONE').length,1)
 report.checks.push('周期表单、工作台完成、下一期唯一生成')
 await page.screenshot({path:join(output,'today-desktop.png'),fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:join(output,'today-mobile.png'),fullPage:true})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'移动端不应横向溢出')
 await today.getByRole('button',{name:'查看全部',exact:true}).click()
 await page.getByText('当前显示今日到期的未完成任务',{exact:true}).waitFor()
 assert.equal(new URL(page.url()).searchParams.get('agenda'),'today')
 await page.getByRole('button',{name:'显示全部日期',exact:true}).click()
 await page.getByRole('row').filter({hasText:'浏览器父任务'}).waitFor()
 assert.equal(new URL(page.url()).searchParams.has('agenda'),false)
 report.checks.push('工作台完整列表筛选与清除')
 await page.screenshot({path:join(output,'tasks-mobile.png'),fullPage:true})
 await page.locator('.el-radio-button').filter({hasText:'看板'}).click()
 await page.locator('.task-board').waitFor()
 await page.screenshot({path:join(output,'board-mobile.png'),fullPage:true})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'看板不应横向溢出')
 report.checks.push('390px移动表格和看板布局')
 assert.deepEqual(report.errors,[])
 report.result='PASS'
}finally{
 writeFileSync(join(output,'report.json'),JSON.stringify(report,null,2))
 await browser?.close();await new Promise((r)=>server.httpServer.close(r))
}
console.log(JSON.stringify(report))
